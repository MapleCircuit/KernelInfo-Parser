"""parser/source_facts.py - What one C file defines and calls, read from its text.

Pure functions, no I/O, run once per Git blob (content-addressed, so a blob shared by many revisions is read
once): by the parser for every `.c` / `.h` blob of an ingested version (Step 6.9, stored in `m_blob_facts` as family
`FAMILY` (1), `core/API.md` section 6; the same pass gives the blob's Kernel API record, `parser/kapi_facts.py`,
family 2, from the same masked text), and by the webapp's source index for blobs of revisions the parser never ingested
(`webapp/backend/services/source_index.py`, `webapp/API.md` section 2.19), which assembles revisions from them.

`extract(text)` -> {
    "d": [[name, line_s, line_e, flags], ...]        functions (flags: 1 static) and macros (flags: 2 function-like
                                                     macro, 4 object-like macro), in file order;
    "c": [[def_idx, callee, line], ...]              direct calls `callee(`, inside definition def_idx;
    "m": [[def_idx, field, line], ...]               calls through a member `->field(` / `.field(`;
    "t": [[struct, table, line, positional, [[field, value, line], ...]], ...]
                                                     designated initializers `struct S table = { .field = value }`
                                                     (`value` an identifier, `&` dropped; arrays of structs and one
                                                     nested level, as `outer.inner`);
}

The scan is lexical: comments, strings and character literals are blanked first; preprocessor lines are set
aside (a `#define` body gives the macro's calls); `#if` branches restart at the brace depth of their `#if`, so
a function head written twice under `#ifdef`/`#else` does not unbalance the file. What it cannot see: calls
generated by macro expansion (the macro is the callee instead, and its body gives the next hop), functions
defined by macros other than `SYSCALL_DEFINEn` / `COMPAT_SYSCALL_DEFINEn` / `BPF_CALL_n`, positional initializers.
"""
from __future__ import annotations

import bisect
import heapq
import itertools
import json
import re
import zlib
from typing import Any

FAMILY = 1
FACTS_FORMAT = 1
F_STATIC, F_MACRO_FN, F_MACRO_OBJ = 1, 2, 4

_MASK = re.compile(r"//[^\n]*|/\*.*?\*/|\"(?:\\.|[^\"\\\n])*\"|'(?:\\.|[^'\\\n])*'", re.S)
_DIRECTIVE = re.compile(r"^[ \t]*#(?:[^\n\\]|\\[^\n]|\\\n)*", re.M)
_DIRECTIVE_KIND = re.compile(r"#[ \t]*(define|if|ifdef|ifndef|elif|else|endif|elifdef|elifndef)\b")
_DEFINE = re.compile(r"#[ \t]*define[ \t]+([A-Za-z_]\w*)(\()?")
_BRACES = re.compile(r"[{}]")
_CALL = re.compile(r"\b([A-Za-z_]\w*)[ \t\n]*\(")
_IDENT_BEFORE = re.compile(r"([A-Za-z_]\w*)[ \t\n]*$")
_STATIC = re.compile(r"\bstatic\b")
# An initializer opens with `= {`; the declaration before it says whether it is a struct table
_TABLE_OPEN = re.compile(r"=[ \t\n]*\{")
_TABLE_HEAD = re.compile(r"struct[ \t\n]+([A-Za-z_]\w*)[ \t\n]+"
                         r"(?:(?:const|__\w+)[ \t\n]+)*"
                         r"([A-Za-z_]\w*)[ \t\n]*(\[[^\]]*\])?[ \t\n]*"
                         r"((?:__\w+(?:\((?:[^()]|\([^()]*\))*\))?[ \t\n]*)*)$")
_ENTRY = re.compile(r"^[ \t\n]*\.[ \t\n]*([A-Za-z_]\w*)[ \t\n]*=[ \t\n]*"
                    r"(?:\([ \t\n]*[A-Za-z_][^()]*\)[ \t\n]*)?"
                    r"(?:(?:__devinit_p|__devexit_p|PTR_IF)[ \t\n]*\([ \t\n]*)?"
                    r"(&[ \t\n]*)?"
                    r"([A-Za-z_]\w*)"
                    r"[ \t\n]*\)?(?:[ \t\n]*,)?$")
_NESTED = re.compile(r"^[ \t\n]*\.[ \t\n]*([A-Za-z_]\w*)[ \t\n]*=[ \t\n]*\{")
_TABLE_TOKENS = re.compile(r"[{}(),]")
_SYSCALL = re.compile(r"^(COMPAT_)?SYSCALL_DEFINE\d$")
_ARCH_SYSCALL = re.compile(r"^ARCH_SYSCALL_DEFINE\d$")
_BPF_CALL = re.compile(r"^BPF_CALL_\d$")
_TRACE_EVENT = re.compile(r"^(TRACE_EVENT|DEFINE_EVENT|DECLARE_EVENT_CLASS)$")
_PER_CPU = re.compile(r"^DEFINE_PER_CPU(?:_[A-Z_]+)?$")
_FIRST_ARG = re.compile(r"\([ \t\n]*([A-Za-z_]\w*)")
_SECOND_ARG = re.compile(r"\([ \t\n]*[^,]+,[ \t\n]*([A-Za-z_]\w*)")
_DYNAMIC_ASSIGN = re.compile(
    r"\b([A-Za-z_]\w*)(?:->|\.)([A-Za-z_]\w*)[ \t\n]*=[ \t\n]*"
    r"(?:\([ \t\n]*[A-Za-z_][^()]*\)[ \t\n]*)?"
    r"(?:(?:__devinit_p|__devexit_p|PTR_IF)[ \t\n]*\([ \t\n]*)?"
    r"(&[ \t\n]*)?"
    r"([A-Za-z_]\w*)[ \t\n]*\)?;"
)

# Not calls: statements, operators, type names and annotations written like calls
NOT_CALLS = frozenset("""
if for while switch return sizeof typeof __typeof__ __typeof alignof _Alignof __alignof__ __alignof defined
asm __asm__ __asm volatile __volatile__ __attribute__ __attribute _Static_assert static_assert _Generic case do else
goto int char void long short unsigned signed float double bool _Bool struct union enum const __builtin_expect
__builtin_constant_p __builtin_offsetof __builtin_types_compatible_p __builtin_choose_expr offsetof __stringify
""".split())
# Annotations written after a parameter list, before the body
ANNOTATIONS = frozenset("""
__attribute__ __attribute __acquires __releases __must_hold __printf __scanf __section __aligned __alloc_size
__diagnose_as __no_sanitize_address __nocfi __cold __malloc __weak __used __maybe_unused __noreturn __pure __const
__nonstring __counted_by __cleanup __free __no_kcsan __no_sanitize_thread __noinline __always_inline __init __exit
""".split())
MAX_HEAD = 600
MAX_TABLE = 400_000


def blank(s: str) -> str:
    """Spaces in place of `s`, newlines kept (offsets and line numbers unchanged)."""
    if "\n" not in s:
        return " " * len(s)
    return "\n".join(" " * len(part) for part in s.split("\n"))


def mask(text: str) -> str:
    """The text with comments, strings and character literals blanked."""
    return _MASK.sub(lambda m: blank(m.group(0)), text)


class _Lines:
    def __init__(self, text: str) -> None:
        self.starts = [0, *itertools.accumulate(len(line) + 1 for line in text.split("\n"))]

    def __call__(self, offset: int) -> int:
        return bisect.bisect_right(self.starts, offset)


def _params_group(head: str) -> tuple[int, int] | None:
    """(open, close) of the last balanced parenthesized group ending `head` (after trailing spaces)."""
    end = len(head.rstrip())
    if end == 0 or head[end - 1] != ")":
        return None
    depth = 0
    for i in range(end - 1, -1, -1):
        c = head[i]
        if c == ")":
            depth += 1
        elif c == "(":
            depth -= 1
            if depth == 0:
                return i, end - 1
    return None


def function_name(head: str) -> tuple[str, int] | None:
    """(name, offset in head) of the function whose body follows `head`, or None when `head` is no function head."""
    for _ in range(4):
        group = _params_group(head)
        if group is None:
            return None
        start, _close = group
        m = _IDENT_BEFORE.search(head, 0, start)
        if not m:
            return None
        name = m.group(1)
        if name in ANNOTATIONS:
            head = head[:m.start()]
            continue
        if name in NOT_CALLS:
            return None
        if _SYSCALL.match(name) or _BPF_CALL.match(name) or _ARCH_SYSCALL.match(name) or _TRACE_EVENT.match(name):
            arg = _FIRST_ARG.match(head, start)
            if not arg:
                return None
            if _BPF_CALL.match(name):
                prefix = ""
            elif _ARCH_SYSCALL.match(name):
                prefix = "arch_sys_"
            elif _TRACE_EVENT.match(name):
                prefix = "trace_"
            elif name.startswith("COMPAT_"):
                prefix = "compat_sys_"
            else:
                prefix = "sys_"
            return prefix + arg.group(1), m.start()
        if _PER_CPU.match(name):
            arg = _SECOND_ARG.match(head, start)
            if arg:
                return arg.group(1), m.start()
        # A declaration, not a definition: `=` (an initializer) outside the parameter list
        if "=" in head[:m.start()]:
            return None
        return name, m.start()
    return None


def _directives(masked: str) -> tuple[list[tuple[int, str]], list[tuple[str, bool, int, int]], list[tuple[int, int]]]:
    """Conditional events [(offset, kind)], macro definitions [(name, function_like, start, end)] and all spans."""
    events: list[tuple[int, str]] = []
    defines: list[tuple[str, bool, int, int]] = []
    spans: list[tuple[int, int]] = []
    for m in _DIRECTIVE.finditer(masked):
        spans.append((m.start(), m.end()))
        k = _DIRECTIVE_KIND.search(masked, m.start(), m.end())
        if not k:
            continue
        kind = k.group(1)
        if kind == "define":
            d = _DEFINE.match(masked, k.start(), m.end())
            if d:
                defines.append((d.group(1), bool(d.group(2)), d.end(), m.end()))
        elif kind in ("if", "ifdef", "ifndef"):
            events.append((m.start(), "if"))
        elif kind in ("elif", "else", "elifdef", "elifndef"):
            events.append((m.start(), "else"))
        else:
            events.append((m.start(), "endif"))
    return events, defines, spans


def _without_directives(masked: str, spans: list[tuple[int, int]]) -> str:
    if not spans:
        return masked
    parts = []
    last = 0
    for a, b in spans:
        parts.append(masked[last:a])
        parts.append(blank(masked[a:b]))
        last = b
    parts.append(masked[last:])
    return "".join(parts)


def _member_before(code: str, pos: int) -> bool:
    """`->` or `.` (spaces allowed) right before offset `pos`: a call through a struct member."""
    j = pos - 1
    while j >= 0 and code[j] in " \t\n":
        j -= 1
    return j >= 0 and (code[j] == "." or (code[j] == ">" and j > 0 and code[j - 1] == "-"))


def _calls(code: str, start: int, end: int, def_idx: int, line_of: _Lines, calls: list, members: list) -> None:
    for m in _CALL.finditer(code, start, end):
        name = m.group(1)
        at = m.start()
        if _member_before(code, at):
            members.append([def_idx, name, line_of(at)])
        elif name not in NOT_CALLS:
            calls.append([def_idx, name, line_of(at)])


def extract(text: str, masked: str | None = None) -> dict[str, Any]:
    """The facts of one C file (see the module docstring); `masked` is `mask(text)` when the caller has it already."""
    if masked is None:
        masked = mask(text)
    line_of = _Lines(masked)
    events, defines, spans = _directives(masked)
    code = _without_directives(masked, spans)
    defs: list[list[Any]] = []
    calls: list[list[Any]] = []
    members: list[list[Any]] = []

    for name, fn_like, body_start, body_end in defines:
        idx = len(defs)
        before = len(calls) + len(members)
        defs.append([name, line_of(body_start), line_of(body_end), F_MACRO_FN if fn_like else F_MACRO_OBJ])
        _calls(masked, body_start, body_end, idx, line_of, calls, members)
        if not fn_like and len(calls) + len(members) == before:
            defs.pop()  # a constant: nothing to follow through it

    depth = 0
    saved: list[int] = []
    current: list[Any] | None = None  # [def_idx, open offset]
    braces = ((m.start(), m.group(0)) for m in _BRACES.finditer(code))
    for pos, kind in heapq.merge(braces, iter(events)):
        if kind == "{":
            if depth == 0:
                floor = max(code.rfind(";", 0, pos), code.rfind("}", 0, pos), code.rfind("{", 0, pos), pos - MAX_HEAD)
                head = code[floor + 1:pos]
                found = function_name(head)
                if current is not None:  # an #else branch reopened a function: the first head's body ends here
                    end = floor + 1 + found[1] if found else pos
                    defs[current[0]][2] = line_of(end)
                    _calls(code, current[1], end, current[0], line_of, calls, members)
                    current = None
                if found:
                    name, off = found
                    flags = F_STATIC if _STATIC.search(head, 0, off) else 0
                    current = [len(defs), pos]
                    defs.append([name, line_of(floor + 1 + off), line_of(pos), flags])
            depth += 1
        elif kind == "}":
            depth = max(0, depth - 1)
            if depth == 0 and current is not None:
                defs[current[0]][2] = line_of(pos)
                _calls(code, current[1], pos, current[0], line_of, calls, members)
                current = None
        elif kind == "if":
            saved.append(depth)
        elif kind == "else":
            if saved:
                depth = saved[-1]
        elif saved:
            saved.pop()
    if current is not None:
        defs[current[0]][2] = line_of(len(code))
        _calls(code, current[1], len(code), current[0], line_of, calls, members)

    assignments: list[list[Any]] = []
    for m in _DYNAMIC_ASSIGN.finditer(code):
        var, field, _amp, val = m.group(1), m.group(2), m.group(3), m.group(4)
        if val not in NOT_CALLS and field not in NOT_CALLS:
            assignments.append([var, field, val, line_of(m.start())])

    return {"d": defs, "c": calls, "m": members, "t": tables(code, line_of), "a": assignments}


# ------------------------------------------------------------------------------------- initializers

def _entries(code: str, open_pos: int, limit: int) -> tuple[list[tuple[int, int]], int]:
    """(start, end) spans of the comma-separated entries directly inside the brace at `open_pos`, and its close."""
    spans: list[tuple[int, int]] = []
    depth = paren = 0
    start = open_pos + 1
    for m in _TABLE_TOKENS.finditer(code, open_pos, min(len(code), open_pos + limit)):
        c = m.group(0)
        if c == "(":
            paren += 1
        elif c == ")":
            paren = max(0, paren - 1)
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                if code[start:m.start()].strip():
                    spans.append((start, m.start()))
                return spans, m.start()
        elif c == "," and depth == 1 and paren == 0:
            if code[start:m.start()].strip():
                spans.append((start, m.start()))
            start = m.end()
    return spans, -1


def _scan(code: str, open_pos: int, prefix: str, line_of: _Lines, out: list, nest: int) -> int:
    """Designated entries of the initializer at `open_pos` into `out`; returns the positional entries counted."""
    spans, _close = _entries(code, open_pos, MAX_TABLE)
    positional = 0
    for a, b in spans:
        entry = code[a:b]
        m = _ENTRY.match(entry)
        if m:
            out.append([prefix + m.group(1), m.group(3), line_of(a + entry.index("."))])
            continue
        n = _NESTED.match(entry)
        if n and nest > 0:
            positional += _scan(code, a + n.end() - 1, f"{prefix}{n.group(1)}.", line_of, out, nest - 1)
            continue
        if not entry.lstrip().startswith((".", "[")):
            positional += 1
    return positional


def _table_head(code: str, eq: int) -> re.Match | None:
    """`struct S name[...] attributes` ending right before the `=` at `eq` (the last `struct` keyword first)."""
    floor = max(0, eq - 400)
    end = eq
    for _ in range(3):
        p = code.rfind("struct", floor, end)
        if p < 0:
            return None
        if p == 0 or not (code[p - 1].isalnum() or code[p - 1] == "_"):
            m = _TABLE_HEAD.match(code, p, eq)
            if m:
                return m
        end = p
    return None


def tables(code: str, line_of: _Lines) -> list[list[Any]]:
    """`struct S name[...] = { ... }` initializers with their designated `.field = identifier` entries."""
    out: list[list[Any]] = []
    for o in _TABLE_OPEN.finditer(code):
        m = _table_head(code, o.start())
        if m is None:
            continue
        open_pos = o.end() - 1
        entries: list[list[Any]] = []
        positional = 0
        if m.group(3):  # an array of structs: each element is one initializer
            spans, _close = _entries(code, open_pos, MAX_TABLE)
            for a, b in spans:
                element = code[a:b]
                brace = element.find("{")
                head = element[:brace] if brace >= 0 else element
                if brace >= 0 and (not head.strip() or re.fullmatch(r"\s*\[[^\]]*\]\s*=\s*", head)):
                    positional += _scan(code, a + brace, "", line_of, entries, 2)
        else:
            positional = _scan(code, open_pos, "", line_of, entries, 2)
        if entries or positional:
            out.append([m.group(1), m.group(2), line_of(m.start()), positional, entries])
    return out


# ------------------------------------------------------------------------------------- worker processes

def init_worker() -> None:
    """Pool initializer: extraction yields the CPU to the server and the parser."""
    import os
    try:
        os.nice(10)
    except OSError:
        pass
    try:
        from core.logging_setup import configure_worker_logging_from_env
        configure_worker_logging_from_env()
    except Exception:
        pass


def extract_many(items: list[tuple[str, str]]) -> list[tuple[str, dict[str, Any] | None]]:
    """[(blob sha, text)] -> [(blob sha, facts)] (None when a file defeats the scanner)."""
    out: list[tuple[str, dict[str, Any] | None]] = []
    for sha, text in items:
        try:
            out.append((sha, extract(text)))
        except (RecursionError, ValueError, IndexError):
            out.append((sha, None))
    return out


EMPTY: dict[str, list[Any]] = {"d": [], "c": [], "m": [], "t": [], "a": []}


def encode(facts: dict[str, Any] | None) -> bytes:
    """Stored form of a blob's facts (`m_blob_facts.data`, the webapp's local store): zlib-compressed JSON."""
    return zlib.compress(json.dumps(facts if facts is not None else EMPTY, separators=(",", ":")).encode(), 3)


def decode(data: bytes | bytearray | memoryview | None) -> dict[str, Any] | None:
    """`encode()` reversed (None when the bytes are not stored facts)."""
    if data is None:
        return None
    try:
        facts = json.loads(zlib.decompress(bytes(data)))
    except (zlib.error, ValueError):
        return None
    return facts if isinstance(facts, dict) else None


def blob_text(raw: bytes) -> str:
    """The text facts are extracted from: UTF-8, undecodable bytes replaced (as the webapp reads blobs)."""
    return raw.decode("utf-8", "replace")
