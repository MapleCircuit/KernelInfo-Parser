_MISSING = object()


class CompressedChangeSetDict(dict):
    """Memory-optimized dictionary that compresses ChangeSet objects in RAM.

    Executed (evacuated) ChangeSets are kept as they are; the others stay uncompressed in a small LRU cache
    and are pickled and zlib-compressed when they leave it. An entry handed out by `[]`/`get()` may be
    mutated by the caller, so an evicted entry is always compressed again.
    """

    @staticmethod
    def _is_evacuated(val: Any) -> bool:
        """Return True if val is an executed ChangeSet whose internal AST buffers are empty."""
        return bool(val is not None and getattr(val, "cs_processed", False) and not getattr(val, "cs", None) and not getattr(val, "store_dict", None))

    def __init__(self, lru_cache_size: int = 500, *args: Any, **kwargs: Any) -> None:
        super().__init__()
        self._all_keys: set[str] = set()
        self._evacuated_store: dict[str, Any] = {}
        self._compressed_store: dict[str, bytes | None] = {}
        self._lru_cache: OrderedDict[str, Any] = OrderedDict()
        self._lru_size = lru_cache_size
        if args or kwargs:
            self.update(*args, **kwargs)

    def _compress(self, key: str, value: Any) -> bool:
        """Pickle and compress `value` into the compressed store (without its process-local references)."""
        saved = {attr: getattr(value, attr, None) for attr in ("gp", "mf", "batch_cs_dict")}
        try:
            for attr, val in saved.items():
                if val is not None:
                    setattr(value, attr, None)
            self._compressed_store[key] = zlib.compress(pickle.dumps(value, protocol=pickle.HIGHEST_PROTOCOL), level=1)
            return True
        except Exception as e:
            logger.warning(f"[CompressedChangeSetDict] Failed to compress '{key}': {e}")
            return False
        finally:
            for attr, val in saved.items():
                if val is not None:
                    setattr(value, attr, val)

    def _place(self, key: str, value: Any) -> None:
        """Store `value` under `key` (evacuated store, or the LRU cache), without evicting."""
        self._all_keys.add(key)
        self._lru_cache.pop(key, None)
        if value is None:
            self._evacuated_store.pop(key, None)
            self._compressed_store[key] = None
        elif self._is_evacuated(value):
            self._compressed_store.pop(key, None)
            self._evacuated_store[key] = value
        else:
            self._evacuated_store.pop(key, None)
            self._lru_cache[key] = value

    def _evict_lru(self) -> None:
        """Compress the oldest LRU entries until the cache fits (evacuated ones move to their own store)."""
        while len(self._lru_cache) > self._lru_size:
            k, v = self._lru_cache.popitem(last=False)
            if self._is_evacuated(v):
                self._compressed_store.pop(k, None)
                self._evacuated_store[k] = v
            elif not self._compress(k, v):
                # Kept uncompressed; stop here rather than retry the same entries forever
                self._lru_cache[k] = v
                break

    def flush(self) -> None:
        """Compress every LRU entry into the compressed store (entries stay cached), e.g. before pickling."""
        for k, v in self._lru_cache.items():
            self._compress(k, v)

    def __reduce__(self) -> tuple[Any, ...]:
        self.flush()
        return (CompressedChangeSetDict, (self._lru_size,), {
            "_all_keys": self._all_keys,
            "_evacuated_store": self._evacuated_store,
            "_compressed_store": self._compressed_store,
            "_lru_cache": OrderedDict(),
            "_lru_size": self._lru_size,
        })

    def _load(self, key: str, default: Any = _MISSING) -> Any:
        if key in self._evacuated_store:
            return self._evacuated_store[key]
        if key in self._lru_cache:
            self._lru_cache.move_to_end(key)
            return self._lru_cache[key]
        if key not in self._compressed_store:
            if default is _MISSING:
                raise KeyError(key)
            return default
        compressed = self._compressed_store[key]
        if compressed is None:
            return None
        obj = pickle.loads(zlib.decompress(compressed))  # noqa: S301
        if self._is_evacuated(obj):
            self._compressed_store.pop(key, None)
            self._evacuated_store[key] = obj
            return obj
        self._lru_cache[key] = obj
        self._evict_lru()
        return obj

    def __setitem__(self, key: str, value: Any) -> None:
        self._place(key, value)
        self._evict_lru()

    def __getitem__(self, key: str) -> Any:
        return self._load(key)

    def get(self, key: str, default: Any = None) -> Any:
        try:
            return self._load(key, default)
        except Exception:
            return default

    def __delitem__(self, key: str) -> None:
        self._all_keys.discard(key)
        self._evacuated_store.pop(key, None)
        self._compressed_store.pop(key, None)
        self._lru_cache.pop(key, None)

    def __contains__(self, key: object) -> bool:
        return key in self._all_keys

    def __len__(self) -> int:
        return len(self._all_keys)

    def __iter__(self):
        return iter(list(self._all_keys))

    def __bool__(self) -> bool:
        return bool(self._all_keys)

    def clear(self) -> None:
        self._all_keys.clear()
        self._evacuated_store.clear()
        self._compressed_store.clear()
        self._lru_cache.clear()

    def keys(self):
        return self._all_keys

    def values(self):
        for k in list(self._all_keys):
            yield self[k]

    def items(self):
        for k in list(self._all_keys):
            yield (k, self[k])

    def update(self, *args: Any, **kwargs: Any) -> None:
        items = list(args[0].items() if args and isinstance(args[0], dict) else (args[0] if args else ()))
        items.extend(kwargs.items())
        for k, v in items:
            self._place(k, v)
        self._evict_lru()

    def pop(self, key: str, *args: Any) -> Any:
        if key in self:
            val = self[key]
            del self[key]
            return val
        if args:
            return args[0]
        raise KeyError(key)

    def setdefault(self, key: str, default: Any = None) -> Any:
        if key in self:
            return self[key]
        self[key] = default
        return default

    def copy(self) -> "CompressedChangeSetDict":
        new_dict = CompressedChangeSetDict(lru_cache_size=self._lru_size)
        new_dict._all_keys = set(self._all_keys)
        new_dict._evacuated_store = dict(self._evacuated_store)
        new_dict._compressed_store = dict(self._compressed_store)
        new_dict._lru_cache = OrderedDict(self._lru_cache)
        return new_dict



class GreatProcessor:
    """Central runtime state container (`gp`) and multiprocessing IPC manager."""

    def __init__(self) -> None:
        """Initialize version state tracking, table array, and manager attributes."""
        self.PURGE_LIST = []
        self.Table_Array = []
        self.Version_Name = "4b825dc642cb6eb9a060e54bf8d69288fbee4904"
        self.Old_Version_Name = 0
        self.VID = 0
        self.Old_VID = 0
        self.Change_List = None
        self.worker_change_list: list[str] | None = None
        self.Symlink_List = []
        self.ChangeSet_Dict = CompressedChangeSetDict(lru_cache_size=500)
        self.Alt_ChangeSet_Dict = CompressedChangeSetDict(lru_cache_size=500)
        self.unchanged_symbol_cache: dict[str, dict[tuple[str, int], int]] = {}
        # Symbol maps of unchanged files by blob id, kept across versions (a blob's rows never change). Workers
        # inherit it when forked, collect what they load in `_blob_symbols_fetched` / `_blob_symbols_used` and
        # send both back with their done frame (`merge_blob_symbols()`).
        self.blob_symbol_cache: dict[int, dict[tuple[str, int], int]] = {}
        # blob id -> version counter (`_blob_symbol_generation`) of its last lookup; unused maps are dropped
        self.blob_symbol_used: dict[int, int] = {}
        self._blob_symbol_generation = 0
        self._blob_symbols_fetched: dict[int, dict[tuple[str, int], int]] = {}
        self._blob_symbols_used: set[int] = set()
        self._changed_paths_set: set[str] = set()
        self._ast_staged_symbols: dict[tuple[str, int], int] = {}
        self._ast_staged_names: dict[str, int] = {}
        self.file_deps: dict[str, set[str]] = {}
        # Operation count of each ingested ChangeSet (cycle-breaking tie-break without decompressing it)
        self.cs_op_counts: dict[str, int] = {}
        self.file_symbols: dict[str, dict[tuple[str, int], int]] = {}
        self.file_names: dict[str, dict[str, int]] = {}
        # Paths whose ChangeSet executed in this update: their symbols are published (file_symbols may be
        # cleared once they move to the shared-memory table, so it cannot tell completion on its own)
        self.completed_paths: set[str] = set()
        self.parsed_blob_ids: set[int] = set()
        self.file_pre_extracted_tags: dict[str, list[tuple[int, int, int, int]]] = {}
        self.file_blob_ids: dict[str, int] = {}
        self._ast_negative_cache: set[tuple[str, int]] = set()
        self._ast_ref_memo: dict[tuple[str, int | None], int | None] = {}
        self._ast_ref_memo_neg_seen: bool = False
        # File-scoped shared memory symbol segments published during Stage 2 (SharedSymbolChain)
        self._shared_symbols = None
        # Commit hash -> commit_id for the version's commit range, registered by ingest_git_dag()
        self.commit_ids_by_hash: dict[str, int] = {}
        # Changed paths whose blob was already parsed and reused by Step 4.5 instead of being parsed again
        self.deduped_paths: set[str] = set()
        # Background git commit parser (`main._git_commit_worker`) and the directory holding its result
        self._commit_proc = None
        self._commit_result_dir: str | None = None

    @staticmethod
    def _cs_lru_size() -> int:
        """Decompressed ChangeSets kept per store for the active G.MEMORY_MODE."""
        if G.VERY_LOW_MEMORY_MODE:
            return 25
        return 50 if G.LOW_MEMORY_MODE else 500

    def _clear_version_symbols(self) -> None:
        """Forget the per-version symbol tables, dependency graph and completion state."""
        self._ast_staged_symbols = {}
        self._ast_staged_names = {}
        self.file_deps = {}
        self.cs_op_counts = {}
        self.file_symbols = {}
        self.file_names = {}
        self.completed_paths = set()
        self.file_pre_extracted_tags = {}
        self.file_blob_ids = {}
        self._ast_negative_cache = set()
        self._ast_ref_memo = {}
        self._ast_ref_memo_neg_seen = False

    def init_cs_dict(self) -> None:
        """Initialize or reset ChangeSet_Dict according to active G.MEMORY_MODE."""
        self.close_shared_symbols()
        self._clear_version_symbols()
        lru_size = self._cs_lru_size()
        self.ChangeSet_Dict = CompressedChangeSetDict(lru_cache_size=lru_size)
        self.Alt_ChangeSet_Dict = CompressedChangeSetDict(lru_cache_size=lru_size)

    def safe_get_cs(self, path: str):
        """ChangeSet of a repository path: the update's own, else one parsed on demand (Alt_ChangeSet_Dict).

        Absolute system paths (headers outside the repository) have none; relative `lib/` and `usr/` are
        kernel directories.
        """
        if not path or path.startswith(("/usr/", "/etc/", "/lib/", "/opt/")):
            return None
        CS = self.ChangeSet_Dict.get(path)
        if CS is None:
            CS = self.Alt_ChangeSet_Dict.get(path)
            if CS is None:
                mf = getattr(self, "mf", None) or getattr(G, "MF", None)
                v_name = getattr(self, "Version_Name", "v3.0")
                if mf and hasattr(mf, "version_dict") and v_name in mf.version_dict:
                    mfdir = mf.version_dict[v_name]
                    target_file = os.path.join(mfdir, path)
                    if not os.path.exists(target_file):
                        return None
                CS = ChangeSet("M", path)
                CS.gp = self
                CS.mf = mf
                try:
                    CS.parse()
                except Exception:
                    pass
                self.Alt_ChangeSet_Dict[path] = CS
        return CS

    def get_file_symbols_from_db(self, rel_file: str) -> dict[tuple[str, int], int] | None:
        """Query DB for symbol mappings (name, type_id) -> ast_id for a file not in active ChangeSet_Dict."""
        if not rel_file:
            return None
        if rel_file in self.unchanged_symbol_cache:
            return self.unchanged_symbol_cache[rel_file]

        from core.DBLayout import m_file_name, m_bridge_file, m_bridge_tag, m_tag, m_ast
        te = getattr(G, "TE", None)
        if te is None or not getattr(te, "tables", None):
            return None
        if m_file_name.table_id not in te.tables or m_bridge_file.table_id not in te.tables:
            return None
        if m_bridge_tag.table_id not in te.tables or m_tag.table_id not in te.tables:
            return None

        fn_row = m_file_name.get(None, rel_file)
        if not fn_row or len(fn_row) < 3 or not fn_row[2]:
            self.unchanged_symbol_cache[rel_file] = {}
            return self.unchanged_symbol_cache[rel_file]
        fnid = fn_row[2][0]

        vid = getattr(self, "VID", 0)
        old_vid = getattr(self, "Old_VID", 0)
        bf_row = m_bridge_file.get(vid, fnid, None)
        if bf_row is None or len(bf_row) < 3 or not bf_row[2]:
            # A file changed in this update has no current-version row until it executes; its previous
            # version's symbols would be stale, so report nothing (and cache nothing) until then.
            if rel_file in getattr(self, "_changed_paths_set", ()):
                return None
            if old_vid > 0:
                bf_row = m_bridge_file.get(old_vid, fnid, None)
        if not bf_row or len(bf_row) < 3 or not bf_row[2]:
            self.unchanged_symbol_cache[rel_file] = {}
            return self.unchanged_symbol_cache[rel_file]
        fid = bf_row[2][2]
        # A file unchanged in this update points at a blob written by an earlier version: its map is final
        # A changed file that executed before this stage's workers forked (Stage 2: the wave pass and the
        # inter-epoch commits wrote its rows before the fork) is as final as an unchanged one for a worker.
        in_committed_stage = getattr(self, "_is_worker", False) and getattr(self, "_shared_symbols", None) is not None
        complete_blob = rel_file not in getattr(self, "_changed_paths_set", ()) or (
            in_committed_stage and rel_file in getattr(self, "completed_paths", ())
        )
        if complete_blob:
            known = self.blob_symbol_cache.get(fid)
            if known is None:
                known = self._blob_symbols_fetched.get(fid)
            if known is not None:
                self._note_blob_symbols_used(fid)
                self.unchanged_symbol_cache[rel_file] = known
                return known

        joins = (
            (m_bridge_tag.tag_id, m_tag.tag_id, 1),
            (m_tag.ast_id, m_ast.ast_id, 1),
        )
        total_cols = m_bridge_tag.length + m_tag.length + m_ast.length
        cols = (fid,) + (None,) * (total_cols - 1)
        rows = m_bridge_tag.view_get_multiple(joins, *cols)
        if not rows:
            if complete_blob:
                self._store_blob_symbols(fid, {})
            self.unchanged_symbol_cache[rel_file] = {}
            return self.unchanged_symbol_cache[rel_file]

        ast_id_idx = m_bridge_tag.length + m_tag.ast_id[1]
        ast_name_idx = m_bridge_tag.length + m_tag.length + m_ast.name[1]
        ast_type_idx = m_bridge_tag.length + m_tag.length + m_ast.type_id[1]

        sym_map: dict[tuple[str, int], int] = {}
        tag_ids: list[int] = []
        for row in rows:
            if len(row) >= total_cols:
                ast_id = row[ast_id_idx]
                ast_name = row[ast_name_idx]
                ast_type = row[ast_type_idx]
                if ast_name and ast_id:
                    sym_map[(ast_name, ast_type)] = ast_id
                tid = row[m_bridge_tag.tag_id[1]]
                if tid:
                    tag_ids.append(tid)

        # Include definitions stored per blob (m_blob_symbol_def)
        from core.DBLayout import m_blob_symbol_def, m_tag_def, m_blob_symbol
        if m_blob_symbol_def.table_id in te.tables:
            b_defs = te.get_in(m_blob_symbol_def.table_id, m_blob_symbol_def.blob_id[1], (fid,)) or ()
            for r in b_defs:
                if len(r) > m_blob_symbol_def.type_id[1]:
                    d_ast_id = r[m_blob_symbol_def.ast_id[1]]
                    d_name = r[m_blob_symbol_def.name[1]]
                    d_type = r[m_blob_symbol_def.type_id[1]]
                    if isinstance(d_name, (bytes, bytearray)):
                        d_name = d_name.decode("utf-8", "replace")
                    if d_name and d_ast_id:
                        sym_map[(d_name, d_type)] = d_ast_id

        # Include definitions stored once per tag (m_tag_def + m_blob_symbol): the blob's key resolutions in
        # one read, plus a staged lookup per key still missing for a blob written in this update
        if tag_ids and m_tag_def.table_id in te.tables and m_blob_symbol.table_id in te.tables:
            t_defs = te.get_in(m_tag_def.table_id, m_tag_def.tag_id[1], tag_ids) or ()
            if t_defs:
                key_col, target_col = m_blob_symbol.sym_key[1], m_blob_symbol.target_ast_id[1]
                targets: dict[int, int | None] = {
                    r[key_col]: r[target_col]
                    for r in te.get_in(m_blob_symbol.table_id, m_blob_symbol.blob_id[1], (fid,)) or ()
                }
                for r in t_defs:
                    key = r[m_tag_def.sym_key[1]]
                    if key not in targets:
                        # A Stage 2 worker has nothing staged for blobs written before its fork
                        bs_row = None if (complete_blob or in_committed_stage) else te.get(m_blob_symbol.table_id, (fid, key, None))
                        targets[key] = bs_row[target_col] if bs_row else None
                    d_ast_id = targets[key]
                    d_name = r[m_tag_def.name[1]]
                    if isinstance(d_name, (bytes, bytearray)):
                        d_name = d_name.decode("utf-8", "replace")
                    if d_ast_id and d_name:
                        sym_map[(d_name, r[m_tag_def.type_id[1]])] = d_ast_id

        if complete_blob:
            self._store_blob_symbols(fid, sym_map)
        self.unchanged_symbol_cache[rel_file] = sym_map
        return sym_map

    def get_files_symbols_from_db_many(
        self, paths: Iterable[str], version: int | None = None
    ) -> dict[str, dict[tuple[str, int], int]]:
        """Bulk-load `(name, type_id) -> ast_id` symbol maps for uncached headers in chunked DB reads."""
        req_paths = [p for p in dict.fromkeys(paths) if p]
        result: dict[str, dict[tuple[str, int], int]] = {}
        pending_paths: list[str] = []
        for p in req_paths:
            if p in self.unchanged_symbol_cache:
                result[p] = self.unchanged_symbol_cache[p]
            else:
                pending_paths.append(p)
        if not pending_paths:
            return result

        from core.DBLayout import (
            m_ast,
            m_blob_symbol,
            m_blob_symbol_def,
            m_bridge_file,
            m_bridge_tag,
            m_file_name,
            m_tag,
            m_tag_def,
        )
        from db_engine.spec import Join

        te = getattr(G, "TE", None)
        if te is None or not getattr(te, "tables", None):
            return result
        if (
            m_file_name.table_id not in te.tables
            or m_bridge_file.table_id not in te.tables
            or m_bridge_tag.table_id not in te.tables
            or m_tag.table_id not in te.tables
        ):
            return result

        db = getattr(te, "db", None)
        if db is None:
            for p in pending_paths:
                sm = self.get_file_symbols_from_db(p)
                if sm is not None:
                    result[p] = sm
            return result

        chunk_size = 1000
        fname_col = m_file_name.fname[1]
        fnid_col = m_file_name.fnid[1]
        path_to_fnid: dict[str, int] = {}
        for i in range(0, len(pending_paths), chunk_size):
            chunk = pending_paths[i : i + chunk_size]
            for r in te.get_in(m_file_name.table_id, fname_col, chunk) or ():
                fn = r[fname_col]
                if isinstance(fn, (bytes, bytearray)):
                    fn = fn.decode("utf-8", "replace")
                fid_val = r[fnid_col]
                if fn and fid_val:
                    path_to_fnid[fn] = int(fid_val)

        for p in pending_paths:
            if p not in path_to_fnid:
                self.unchanged_symbol_cache[p] = {}
                result[p] = {}

        if not path_to_fnid:
            return result

        vid = int(version if version is not None else (getattr(self, "VID", 0) or 0))
        old_vid = int(getattr(self, "Old_VID", 0) or 0)
        changed_paths = getattr(self, "_changed_paths_set", ())
        in_committed_stage = bool(getattr(self, "_is_worker", False) and getattr(self, "_shared_symbols", None) is not None)
        completed_paths = getattr(self, "completed_paths", ())

        fnid_to_paths: dict[int, list[str]] = {}
        for p, fnid in path_to_fnid.items():
            fnid_to_paths.setdefault(fnid, []).append(p)

        all_fnids = sorted(fnid_to_paths)
        fnid_to_blob: dict[int, int] = {}
        if vid > 0 and all_fnids:
            for i in range(0, len(all_fnids), chunk_size):
                chunk = all_fnids[i : i + chunk_size]
                for fnid, bid in db.select_rows(
                    m_bridge_file.table_name, ["fnid", "blob_id"], {"commit_id": vid, "fnid": chunk}, as_dict=False
                ):
                    if bid:
                        fnid_to_blob[int(fnid)] = int(bid)

        if old_vid > 0:
            fallback_fnids = sorted(
                fnid
                for fnid, ps in fnid_to_paths.items()
                if fnid not in fnid_to_blob and any(p not in changed_paths for p in ps)
            )
            for i in range(0, len(fallback_fnids), chunk_size):
                chunk = fallback_fnids[i : i + chunk_size]
                for fnid, bid in db.select_rows(
                    m_bridge_file.table_name, ["fnid", "blob_id"], {"commit_id": old_vid, "fnid": chunk}, as_dict=False
                ):
                    if bid:
                        fnid_to_blob[int(fnid)] = int(bid)

        blobs_to_load: dict[int, bool] = {}
        blob_to_paths: dict[int, list[str]] = {}
        for p, fnid in path_to_fnid.items():
            fid = fnid_to_blob.get(fnid)
            if fid is None:
                if p in changed_paths:
                    continue
                self.unchanged_symbol_cache[p] = {}
                result[p] = {}
                continue

            complete_blob = (p not in changed_paths) or (in_committed_stage and p in completed_paths)
            if complete_blob:
                known = self.blob_symbol_cache.get(fid)
                if known is None:
                    known = self._blob_symbols_fetched.get(fid)
                if known is not None:
                    self._note_blob_symbols_used(fid)
                    self.unchanged_symbol_cache[p] = known
                    result[p] = known
                    continue

            blobs_to_load[fid] = blobs_to_load.get(fid, False) or complete_blob
            blob_to_paths.setdefault(fid, []).append(p)

        if not blobs_to_load:
            return result

        fids = sorted(blobs_to_load)
        sym_maps: dict[int, dict[tuple[str, int], int]] = {fid: {} for fid in fids}
        blob_tag_ids: dict[int, list[int]] = {fid: [] for fid in fids}
        all_tag_ids: set[int] = set()

        joins = [
            Join(("m_tag", "t"), {"t.tag_id": "b.tag_id"}),
            Join(("m_ast", "a"), {"a.ast_id": "t.ast_id"}),
        ]
        for i in range(0, len(fids), chunk_size):
            chunk = fids[i : i + chunk_size]
            rows = db.select_rows(
                ("m_bridge_tag", "b"),
                ["b.blob_id", "b.tag_id", "a.ast_id", "a.name", "a.type_id"],
                {"b.blob_id": chunk},
                joins=joins,
                as_dict=False,
            )
            for fid, tid, ast_id, ast_name, ast_type in rows:
                if isinstance(ast_name, (bytes, bytearray)):
                    ast_name = ast_name.decode("utf-8", "replace")
                if ast_name and ast_id:
                    sym_maps[fid][(ast_name, ast_type)] = ast_id
                if tid:
                    blob_tag_ids[fid].append(tid)
                    all_tag_ids.add(tid)

        if m_blob_symbol_def.table_id in te.tables:
            bsd_blob = m_blob_symbol_def.blob_id[1]
            bsd_ast = m_blob_symbol_def.ast_id[1]
            bsd_name = m_blob_symbol_def.name[1]
            bsd_type = m_blob_symbol_def.type_id[1]
            for i in range(0, len(fids), chunk_size):
                chunk = fids[i : i + chunk_size]
                for r in te.get_in(m_blob_symbol_def.table_id, bsd_blob, chunk) or ():
                    if len(r) > bsd_type:
                        d_ast_id = r[bsd_ast]
                        d_name = r[bsd_name]
                        d_type = r[bsd_type]
                        if isinstance(d_name, (bytes, bytearray)):
                            d_name = d_name.decode("utf-8", "replace")
                        if d_name and d_ast_id:
                            sym_maps[r[bsd_blob]][(d_name, d_type)] = d_ast_id

        if all_tag_ids and m_tag_def.table_id in te.tables and m_blob_symbol.table_id in te.tables:
            tag_defs_by_tid: dict[int, list[tuple[int, str, int]]] = {}
            sorted_tids = sorted(all_tag_ids)
            td_tid = m_tag_def.tag_id[1]
            td_key = m_tag_def.sym_key[1]
            td_name = m_tag_def.name[1]
            td_type = m_tag_def.type_id[1]
            for i in range(0, len(sorted_tids), chunk_size):
                chunk = sorted_tids[i : i + chunk_size]
                for r in te.get_in(m_tag_def.table_id, td_tid, chunk) or ():
                    d_name = r[td_name]
                    if isinstance(d_name, (bytes, bytearray)):
                        d_name = d_name.decode("utf-8", "replace")
                    if d_name:
                        tag_defs_by_tid.setdefault(r[td_tid], []).append((r[td_key], d_name, r[td_type]))

            if tag_defs_by_tid:
                bs_blob = m_blob_symbol.blob_id[1]
                bs_key = m_blob_symbol.sym_key[1]
                bs_target = m_blob_symbol.target_ast_id[1]
                targets_by_blob: dict[int, dict[int, int | None]] = {fid: {} for fid in fids}
                for i in range(0, len(fids), chunk_size):
                    chunk = fids[i : i + chunk_size]
                    for r in te.get_in(m_blob_symbol.table_id, bs_blob, chunk) or ():
                        targets_by_blob[r[bs_blob]][r[bs_key]] = r[bs_target]

                for fid in fids:
                    targets = targets_by_blob[fid]
                    complete_blob = blobs_to_load[fid]
                    sm = sym_maps[fid]
                    for tid in blob_tag_ids[fid]:
                        for key, d_name, d_type in tag_defs_by_tid.get(tid, ()):
                            if key not in targets:
                                bs_row = None if (complete_blob or in_committed_stage) else te.get(m_blob_symbol.table_id, (fid, key, None))
                                targets[key] = bs_row[bs_target] if bs_row else None
                            d_ast_id = targets[key]
                            if d_ast_id:
                                sm[(d_name, d_type)] = d_ast_id

        for fid, sm in sym_maps.items():
            if blobs_to_load[fid]:
                self._store_blob_symbols(fid, sm)
            for p in blob_to_paths[fid]:
                self.unchanged_symbol_cache[p] = sm
                result[p] = sm

        return result

    def _store_blob_symbols(self, fid: int, sym_map: dict[tuple[str, int], int]) -> None:
        """Keep a complete blob's symbol map: in the cache (parent), or to send to the parent (worker)."""
        if getattr(self, "_is_worker", False):
            self._blob_symbols_fetched[fid] = sym_map
        else:
            self.blob_symbol_cache[fid] = sym_map
        self._note_blob_symbols_used(fid)

    def _note_blob_symbols_used(self, fid: int) -> None:
        if getattr(self, "_is_worker", False):
            self._blob_symbols_used.add(fid)
        else:
            self.blob_symbol_used[fid] = self._blob_symbol_generation

    def merge_blob_symbols(self, fetched: dict[int, dict[tuple[str, int], int]] | None, used: Iterable[int] | None) -> None:
        """Add the symbol maps a worker loaded, and mark the blobs it looked up as used in this version."""
        if fetched:
            for fid, sym_map in fetched.items():
                self.blob_symbol_cache.setdefault(fid, sym_map)
        generation = self._blob_symbol_generation
        for fid in itertools.chain(fetched or (), used or ()):
            self.blob_symbol_used[fid] = generation

    def prune_blob_symbol_cache(self, max_idle_versions: int = 8) -> int:
        """Start the next version's counter and drop maps no lookup used in the last `max_idle_versions` versions.

        Returns:
            Number of blob maps dropped.
        """
        self._blob_symbol_generation += 1
        oldest = self._blob_symbol_generation - max_idle_versions
        stale = [fid for fid in self.blob_symbol_cache if self.blob_symbol_used.get(fid, -1) < oldest]
        for fid in stale:
            del self.blob_symbol_cache[fid]
            self.blob_symbol_used.pop(fid, None)
        return len(stale)

    def reset_cs(self) -> None:
        """Reset Change_List, ChangeSet stores and per-version symbol state once a version is parsed."""
        self.Alt_ChangeSet_Dict.clear()
        self.unchanged_symbol_cache.clear()
        self.prune_blob_symbol_cache()
        self._clear_version_symbols()
        self.Change_List = None
        self.worker_change_list = None
        self.commit_ids_by_hash = {}
        self.deduped_paths = set()
        self.Symlink_List.clear()
        self.stop_commit_worker()
        self.close_shared_symbols()
        self.ChangeSet_Dict.clear()

    def close_shared_symbols(self) -> None:
        """Unmap the shared memory symbol segments so they never leak into the next version."""
        shared = getattr(self, "_shared_symbols", None)
        self._shared_symbols = None
        if shared is not None:
            try:
                shared.close()
            except Exception as e:
                logger.debug(f"Closing shared symbol table failed: {e}")

    def stop_commit_worker(self) -> None:
        """Terminate the background git commit parser if still running and delete its result directory."""
        proc = getattr(self, "_commit_proc", None)
        self._commit_proc = None
        if proc is not None:
            try:
                if proc.is_alive():
                    proc.terminate()
                proc.join(timeout=5.0)
            except Exception:
                pass
        result_dir = getattr(self, "_commit_result_dir", None)
        self._commit_result_dir = None
        if result_dir:
            shutil.rmtree(result_dir, ignore_errors=True)
            if result_dir in self.PURGE_LIST:
                self.PURGE_LIST.remove(result_dir)
