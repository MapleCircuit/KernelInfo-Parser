#!/usr/bin/env python3
"""toc.py - (re)generate the line-indexed "Table of Contents" block of a spec from its headings.

Usage:
    python3 .agents/scripts/toc.py --write <spec.md> [<spec.md> ...]   # regenerate the TOC block in place
    python3 .agents/scripts/toc.py --check <spec.md|all>               # exit 1 when a TOC is stale (prints the fix)
    python3 .agents/scripts/toc.py --write all                         # every spec that has a TOC

Style (one for every spec): below `## Table of Contents`, a generated block between the markers
`<!-- toc:begin -->` and `<!-- toc:end -->` lists every `##` and `###` heading as
`- <heading text> [L<first>-L<last>]` (children indented two spaces; the range covers the whole section including
its subsections). Everything between the markers is generated: edit headings, then run `--write`.
Read a section with `python3 .agents/scripts/spec_section.py <spec.md> <section number or title>`.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from spec_section import parse_headings  # noqa: E402

TOC_HEADING = "## Table of Contents"
BEGIN = "<!-- toc:begin (generated by .agents/scripts/toc.py; edit headings, then run --write) -->"
END = "<!-- toc:end -->"
SPEC_DIRS = ("core", "db_engine", "cache_engine", "parser", "table_engine", "webapp")


def spec_files(root: Path = ROOT) -> list[Path]:
    """Every markdown file under the subsystem directories that carries a `## Table of Contents` heading."""
    found = []
    for d in SPEC_DIRS:
        for p in sorted((root / d).rglob("*.md")):
            if "node_modules" in p.parts:
                continue
            if TOC_HEADING in p.read_text(encoding="utf-8").splitlines():
                found.append(p)
    return found


def _entries(lines: list[str], toc_line: int, end_line: int) -> list[str]:
    """TOC entries for `lines` (1-based `toc_line` = TOC heading index) with ranges; excludes the TOC heading itself."""
    total = len(lines)
    heads = [h for h in parse_headings(lines) if h["level"] in (2, 3) and h["line"] != toc_line]
    allh = parse_headings(lines)
    out = []
    for h in heads:
        end = total
        for n in allh:
            if n["line"] > h["line"] and n["level"] <= h["level"]:
                end = n["line"] - 1
                break
        indent = "  " * (h["level"] - 2)
        out.append(f"{indent}- {h['text']} [L{h['line']}-L{end}]")
    return out


def render(text: str) -> str:
    """Return `text` with its TOC block regenerated (fixed point: the block's own height shifts the ranges)."""
    lines = text.split("\n")
    try:
        t = lines.index(TOC_HEADING)
    except ValueError:
        raise SystemExit("no '## Table of Contents' heading")
    # region = lines after the heading up to the first '---' line
    j = t + 1
    while j < len(lines) and lines[j].strip() != "---":
        j += 1
    if j >= len(lines):
        raise SystemExit("TOC block has no closing '---' line")
    for _ in range(6):
        entries = _entries(lines, t + 1, j)
        block = [BEGIN, *entries, END, ""]
        new = lines[: t + 1] + block + lines[j:]
        if new == lines:
            break
        lines = new
        j = t + 1
        while lines[j].strip() != "---":
            j += 1
    return "\n".join(lines)


def check_file(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    return render(text) == text


def main(argv: list[str]) -> int:
    if len(argv) < 2 or argv[0] not in ("--write", "--check"):
        print(__doc__)
        return 2
    mode, targets = argv[0], argv[1:]
    paths = spec_files() if targets == ["all"] else [Path(t) for t in targets]
    rc = 0
    for p in paths:
        if not p.is_file():
            print(f"error: not a file: {p}", file=sys.stderr)
            return 2
        text = p.read_text(encoding="utf-8")
        new = render(text)
        rel = p.resolve().relative_to(ROOT) if p.resolve().is_relative_to(ROOT) else p
        if mode == "--write":
            if new != text:
                p.write_text(new, encoding="utf-8")
                print(f"updated {rel}")
        elif new != text:
            print(f"stale TOC: {rel} (run: python3 .agents/scripts/toc.py --write {rel})")
            rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
